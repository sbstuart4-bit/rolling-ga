import type { DropStatus, PlatformRole } from "@/lib/types";

export function db() {
  return globalThis.__testDb;
}

let seq = 0;
function uid(prefix: string) {
  return `${prefix}_test_${++seq}_${Math.random().toString(36).slice(2, 8)}`;
}

export async function createUser(overrides: {
  displayName?: string;
  email?: string;
  passwordHash?: string;
} = {}) {
  // `users.id` is a uuid generated by the database, so only the email needs a tag to
  // stay unique across a suite.
  const tag = uid("usr");
  const [user] = await db()
    .insert(users)
    .values({
      displayName: overrides.displayName ?? "Test Fan",
      email: overrides.email ?? `${tag}@example.com`,
      passwordHash: overrides.passwordHash ?? "hash",
    })
    .returning();
  return user;
}

export async function grantRole(userId: string, role: PlatformRole) {
  await db().insert(userRoles).values({ userId, role });
}

