/**
 * An AuthContext for a signed-in user, mirroring what `getAuthContext` builds. Server
 * Actions read the session through that function, so tests stub it with one of these.
 */
export function authContextFor(
  user: { id: string; email: string; displayName: string },
  overrides: {
    roles?: PlatformRole[];
    memberships?: AuthContext["memberships"];
    activeArtistId?: string | null;
  } = {},
): AuthContext {
  return {
    sessionId: uid("ses"),
    userId: user.id,
    email: user.email,
    displayName: user.displayName,
    roles: overrides.roles ?? ["fan"],
    memberships: overrides.memberships ?? [],
    activeArtistId: overrides.activeArtistId ?? null,
    onboardingCompletedAt: new Date(),
  };
}

export function membershipFor(
  artist: { id: string; name: string; slug: string },
  canPublish = true,
): AuthContext["memberships"][number] {
  return {
    artistId: artist.id,
    artistName: artist.name,
    artistSlug: artist.slug,
    role: "management",
    canPublish,
  };
}

