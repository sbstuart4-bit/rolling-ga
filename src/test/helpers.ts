export async function setFanShippingAddress(
  userId: string,
  address: {
    shippingName?: string;
    shippingLine1?: string;
    shippingLine2?: string;
    shippingCity?: string;
    shippingRegion?: string;
    shippingPostalCode?: string;
    shippingCountry?: string;
  },
) {
  await db()
    .insert(fanPreferences)
    .values({ userId, ...address })
    .onConflictDoUpdate({
      target: fanPreferences.userId,
      set: address,
    });
}

export async function getFanShippingAddress(userId: string) {
  const [row] = await db()
    .select({
      shippingName: fanPreferences.shippingName,
      shippingLine1: fanPreferences.shippingLine1,
      shippingLine2: fanPreferences.shippingLine2,
      shippingCity: fanPreferences.shippingCity,
      shippingRegion: fanPreferences.shippingRegion,
      shippingPostalCode: fanPreferences.shippingPostalCode,
      shippingCountry: fanPreferences.shippingCountry,
    })
    .from(fanPreferences)
    .where(eq(fanPreferences.userId, userId))
    .limit(1);
  return row ?? null;
}

export async function setFanApparelSize(userId: string, apparelSize: string) {
  await db()
    .insert(fanPreferences)
    .values({ userId, apparelSize })
    .onConflictDoUpdate({
      target: fanPreferences.userId,
      set: { apparelSize },
    });
}

export async function getFanApparelSize(userId: string) {
  const [row] = await db()
    .select({ apparelSize: fanPreferences.apparelSize })
    .from(fanPreferences)
    .where(eq(fanPreferences.userId, userId))
    .limit(1);
  return row?.apparelSize ?? null;
}
